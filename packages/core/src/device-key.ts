/**
 * The device key of Beeper (BIP-F-15, BIP-F-18) — ONE implementation, shared
 * by the PWA (`@bipeur/pager`) and the emulator (`@bipeur/pager-emu`).
 *
 * The private key is generated non-extractable: WebCrypto keeps it inside the
 * process and never lets JavaScript read it, so a stolen `localStorage` is not
 * a stolen pager. The public half travels as a JWK and is what the Central
 * verifies. The signature is the raw `r||s` (IEEE P1363) of the WebCrypto,
 * base64 encoded — the format `verifyDecisionSignature` reads.
 *
 * Nothing here touches the DOM: only `globalThis.crypto.subtle`, the standard
 * `TextEncoder` and `btoa`. The same code runs in a browser, in Node and in a
 * test — that is why it lives in the core and not in the PWA.
 */

/** The tiny slice of WebCrypto we need, injected so tests can control it. */
export interface CryptoPort {
  subtle: Pick<SubtleCrypto, 'generateKey' | 'exportKey' | 'sign' | 'importKey'>;
  getRandomValues(bytes: Uint8Array): Uint8Array;
}

/** The keys of a device: the private half never leaves the process. */
export interface DeviceKeys {
  /** The id the device made up for itself (`dev_…`). */
  deviceId: string;
  /** The private half: non-extractable, and never serialised. */
  privateKey: CryptoKey;
  /** The public half, as the Central wants it: no secret in it. */
  publicKeyJwk: JsonWebKey;
  /** The WebCrypto that made the pair: it is the one that signs with it. */
  crypto: CryptoPort;
}

export const ECDSA_ALGORITHM = { name: 'ECDSA', namedCurve: 'P-256' } as const;
export const SIGN_ALGORITHM = { name: 'ECDSA', hash: 'SHA-256' } as const;

/** Raised instead of silently falling back to something weaker. */
export class DeviceKeyUnavailable extends Error {
  constructor() {
    super('WebCrypto cannot create a non-extractable ECDSA P-256 key');
    this.name = 'DeviceKeyUnavailable';
  }
}

/** The slice of a full `Crypto` the device key needs. */
export function cryptoPort(cryptoImpl: Crypto): CryptoPort {
  return {
    subtle: cryptoImpl.subtle,
    getRandomValues: (bytes) => cryptoImpl.getRandomValues(bytes),
  };
}

/**
 * The WebCrypto of the runtime — the browser's, or Node's — or `null` when it
 * is missing (an old or stripped build). No DOM: `globalThis` only.
 */
export function browserCrypto(): CryptoPort | null {
  const globalCrypto = (globalThis as { crypto?: Crypto }).crypto;
  if (!globalCrypto?.subtle) return null;
  return cryptoPort(globalCrypto);
}

/** Can this port make the key pair the pairing needs? */
export function supportsDeviceKeys(port: CryptoPort | null): port is CryptoPort {
  return port !== null && typeof port.subtle?.generateKey === 'function';
}

/** Hex string of random bytes, as the device ids of the pager are made of. */
export function randomHex(port: CryptoPort, byteLength: number): string {
  const bytes = port.getRandomValues(new Uint8Array(byteLength));
  return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
}

/**
 * Create the key pair of a device.
 *
 * `extractable: false` applies to the private key only: WebCrypto always keeps
 * the public key exportable, which is exactly what the pairing needs.
 */
export async function generateDeviceKeys(port: CryptoPort): Promise<DeviceKeys> {
  if (!supportsDeviceKeys(port)) throw new DeviceKeyUnavailable();
  const keyPair = (await port.subtle.generateKey(ECDSA_ALGORITHM, false, [
    'sign',
    'verify',
  ])) as CryptoKeyPair;
  const publicKeyJwk = await port.subtle.exportKey('jwk', keyPair.publicKey);
  return {
    deviceId: `dev_${randomHex(port, 8)}`,
    privateKey: keyPair.privateKey,
    publicKeyJwk,
    crypto: port,
  };
}

/**
 * Import the key pair a demo space hands over. The demo is the one place where
 * the private key is extractable: it is generated by the Central for an
 * isolated, 24-hour visitor space, never for a real pairing (BIP-F-15 keeps
 * the real key non-extractable and never leaves the device).
 */
export async function importDeviceKeys(
  port: CryptoPort,
  privateJwk: JsonWebKey,
  deviceId: string,
): Promise<DeviceKeys> {
  if (!supportsDeviceKeys(port)) throw new DeviceKeyUnavailable();
  const privateKey = await port.subtle.importKey('jwk', privateJwk, ECDSA_ALGORITHM, false, [
    'sign',
  ]);
  return {
    deviceId,
    privateKey,
    publicKeyJwk: publicJwkOf(privateJwk),
    crypto: port,
  };
}

/**
 * The public half of a private JWK: the same key, without the secret. The
 * Central must never see the `d` member — not even as an empty one.
 */
export function publicJwkOf(privateJwk: JsonWebKey): JsonWebKey {
  const publicJwk: JsonWebKey = {};
  for (const member of ['kty', 'crv', 'x', 'y'] as const) {
    const value = privateJwk[member];
    if (typeof value === 'string') publicJwk[member] = value;
  }
  return publicJwk;
}

/**
 * Sign the exact bytes of a decision, base64 encoded (raw `r||s`).
 *
 * A fresh array, so the buffer is a plain ArrayBuffer and not a view on a
 * shared one: WebCrypto refuses the second.
 */
export async function signBytes(keys: DeviceKeys, data: Uint8Array): Promise<string> {
  const bytes = new Uint8Array(data);
  const raw = await keys.crypto.subtle.sign(SIGN_ALGORITHM, keys.privateKey, bytes);
  return toBase64(raw);
}

/** Sign the exact bytes of a decision (see `decisionSigningString`). */
export async function signClaims(keys: DeviceKeys, signingString: string): Promise<string> {
  return signBytes(keys, new TextEncoder().encode(signingString));
}

/** Single-use nonce: 16 random bytes, hex encoded (32 characters). */
export function newNonce(port: CryptoPort): string {
  return randomHex(port, 16);
}

function toBase64(buffer: ArrayBuffer): string {
  let binary = '';
  for (const byte of new Uint8Array(buffer)) binary += String.fromCharCode(byte);
  return btoa(binary);
}
